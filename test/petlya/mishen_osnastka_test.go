// Пакет petlya поднимает пару «сервер плюс клиент» на 127.0.0.1 и гоняет через
// неё байты. Он отвечает на вопросы, которые сегодня задаются живому VPS через
// домашнюю сеть: несёт ли транспорт, доезжает ли выбор до ядра, меняется ли
// несущий. Это вопросы к НАШЕМУ коду, и стоить они должны секунды.
//
// Правило пакета, нарушать нельзя: он работает на рабочей машине владельца.
// Значит только 127.0.0.1, только случайные порты, гашение строго по своему PID,
// и ни TUN, ни маршрутов, ни брандмауэра, ни системного прокси, ни службы.
//
// ВСЕ файлы пакета, включая оснастку, названы `_test.go` намеренно. Оснастка
// приёмки это не продукт, и ворота мёртвого экспорта справедливо объявили её
// экспорт «написанным и выключенным»: снаружи тестов его действительно никто не
// зовёт и звать не должен. Суффикс делает это фактом для компоновщика, а не
// записью в списке исключений, и заодно отнимает возможность заимпортить
// оснастку в продукт.
package petlya

import (
	"io"
	"net/http"
	"net/http/httptest"
	"testing"
)

// Mishen это то, куда идёт трафик вместо интернета.
//
// Отдаёт своё имя и больше ничего. Имя, а не адрес: у всех наших входов на VPS
// внешний адрес ОДИН, поэтому сегодняшний судья переключения не может отличить
// сервер A от сервера B и печатает НЕГОДЕН с 0.7.0. Две мишени с разными именами
// снимают это ограничение целиком, и заодно убирают из вердикта чужой сайт.
type Mishen struct {
	// Adres это прямой адрес с петлевым IP.
	Adres string
	Imya  string
	// Host это петлевой адрес, на котором мишень стоит. По нему сервер узла
	// разводит общее имя в СВОЮ мишень.
	Host string
	// PoImeni это тот же адрес, но через общее имя мишени. Запрос к A и запрос
	// к B обязаны выглядеть одинаково, иначе проверяется клиент, а не выбор.
	PoImeni string
}

// NovayaMishen поднимает мишень на свободном порту петли и гасит её сама.
func NovayaMishen(t *testing.T, imya string) *Mishen {
	t.Helper()
	s := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		// Без кэширования: ответ читают несколько раз подряд и ждут свежий.
		w.Header().Set("Cache-Control", "no-store")
		io.WriteString(w, imya)
	}))
	t.Cleanup(s.Close)
	return &Mishen{Adres: s.URL, Imya: imya, Host: "127.0.0.1"}
}

// SprositImya ходит в мишень напрямую, без прокси. Нужна там, где проверяется
// сама оснастка; трафик продукта идёт через клиентский вход, а не отсюда.
func SprositImya(t *testing.T, adres string) string {
	t.Helper()
	otvet, err := http.Get(adres)
	if err != nil {
		t.Fatalf("мишень %s не ответила: %v", adres, err)
	}
	defer otvet.Body.Close()
	telo, err := io.ReadAll(otvet.Body)
	if err != nil {
		t.Fatalf("тело мишени %s не прочиталось: %v", adres, err)
	}
	return string(telo)
}
