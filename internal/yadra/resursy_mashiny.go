package yadra

import (
	"errors"
	"syscall"
)

// Коды Winsock, означающие «у машины кончились ресурсы под сокет».
//
// Список короткий НАМЕРЕННО. Сюда нельзя добавлять WSAECONNREFUSED: он значит,
// что ядро не слушает, то есть настоящую аварию, которую чинят подъёмом.
// Ошибиться в эту сторону значит перестать возвращать туннель после смерти
// ядра, и заметить это будет некому.
const (
	wsaeMfile   = syscall.Errno(10024) // слишком много дескрипторов
	wsaeAddrInU = syscall.Errno(10048) // адрес занят: свободных портов нет
	wsaeNoBufs  = syscall.Errno(10055) // не хватило буферов или очередь полна
)

// ResursyMashiny отвечает, что сокет не открылся из-за нехватки ресурсов
// МАШИНЫ, а не из-за того, что туннель перестал нести.
//
// Разница не косметическая. Наблюдатель опускает туннель и перезапускает ядро
// по двум провалам замера подряд, а замер ходит в clash_api на 127.0.0.1.
// Кончились эфемерные порты, и локальный запрос не уходит никуда: туннель при
// этом жив, но получает перезапуск и рвёт человеку все соединения.
//
// Замерено на живой машине 10.09.2026 по журналу за полтора суток: 197 таких
// отказов и 25 разрывов туннеля следом, ровно раз в 98 минут. Столько нужно,
// чтобы утечка со скоростью 2.79 соединения в секунду съела 16384 эфемерных
// порта. Утечка починена, спусковой крючок остался: любой другой пожиратель
// портов на машине даст тот же ложный разрыв.
//
// Опознание идёт по числовому коду, а не по тексту: текст Winsock приходит на
// языке системы, и разбор по подстроке молча перестал бы работать на
// английской машине. Этим уже обжигались на языке гостя, см. set/ipv6.go.
//
// Обёртки разворачиваются любой глубины: ошибка приходит сюда из-под
// fmt.Errorf, net.OpError и os.SyscallError разом.
func ResursyMashiny(err error) bool {
	var errno syscall.Errno
	if !errors.As(err, &errno) {
		return false
	}
	switch errno {
	case wsaeMfile, wsaeAddrInU, wsaeNoBufs:
		return true
	}
	// ENOBUFS и EMFILE на не-Windows: пакет собирается под все системы.
	return errors.Is(errno, syscall.ENOBUFS) || errors.Is(errno, syscall.EMFILE)
}
