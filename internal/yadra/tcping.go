package yadra

import (
	"context"
	"errors"
	"fmt"
	"net"
	"strconv"
	"time"
)

// ErrUzelMolchit значит: до узла не дошло само TCP-соединение. Это НЕ про
// протокол, ключи и рукопожатие, до них дело не дошло вовсе.
var ErrUzelMolchit = errors.New("узел не отвечает на соединение")

// Tcping меряет время установления TCP-соединения до узла, МИМО туннеля.
//
// Второе число рядом с Zaderzhka, и они отвечают на разные вопросы. Zaderzhka
// спрашивает ядро, сколько занял запрос ЧЕРЕЗ туннель, то есть меряет весь путь
// вместе с протоколом и рукопожатием. Tcping меряет только дорогу до узла.
//
// Одно число вместо двух врёт про оба. Сервер, отвечающий на TCP мгновенно и не
// несущий ни байта, это обычный случай: так выглядит отвергнутое рукопожатие,
// просроченный ключ, чужой sid у REALITY. По одной цифре «через туннель» такой
// сервер неотличим от далёкого, но исправного, и человек чинит не то.
//
// Главное свойство: туннель для этого замера НЕ НУЖЕН. Значит кнопка
// «проверить» работает до подключения, то есть тогда, когда человеку и надо
// выбрать, куда подключаться.
//
// Отмена уважается по-настоящему: сорок серверов по кнопке это сорок замеров, и
// висящая очередь после отмены хуже, чем отсутствие кнопки.
func Tcping(ctx context.Context, host string, port int, srok time.Duration) (time.Duration, error) {
	if host == "" {
		return 0, fmt.Errorf("%w: пустой адрес", ErrUzelMolchit)
	}
	if port < 1 || port > 65535 {
		return 0, fmt.Errorf("%w: порт %d вне 1..65535", ErrUzelMolchit, port)
	}
	d := net.Dialer{Timeout: srok}
	adres := net.JoinHostPort(host, strconv.Itoa(port))

	nachalo := time.Now()
	c, err := d.DialContext(ctx, "tcp", adres)
	proshlo := time.Since(nachalo)
	if err != nil {
		// Адрес в текст не попадает: причина отказа доезжает до экрана, а узел
		// подписки это то же, что ключ. Своя ошибка оборачивает чужую, чтобы
		// errors.Is работал, а errors.As достал подробности при разборе.
		return 0, fmt.Errorf("%w: %v", ErrUzelMolchit, korotko(err))
	}
	c.Close()
	// Ноль здесь невозможен на практике, но если часы дали ноль, отдаём
	// наименьшее положительное: ноль на экране читается как «мгновенно», то
	// есть ставит узел первым по задержке.
	if proshlo <= 0 {
		proshlo = time.Nanosecond
	}
	return proshlo, nil
}

// korotko снимает с ошибки сети адрес, оставляя причину.
//
// net.OpError печатает «dial tcp 198.51.100.7:443: ...», то есть узел целиком.
// Этот текст уезжает в кадр ответа и на экран, а узел подписки скрывается по
// той же причине, что и сам адрес подписки.
func korotko(err error) error {
	var oe *net.OpError
	if errors.As(err, &oe) && oe.Err != nil {
		return oe.Err
	}
	return err
}
