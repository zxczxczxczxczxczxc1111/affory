package yadra

import (
	"errors"
	"syscall"
)

// wsaeConnRefused означает «на порту никто не слушает»: процесс ядра уже
// завершён, и петлевой запрос отвергает сама система, не дойдя до сокета.
const wsaeConnRefused = syscall.Errno(10061)

// YadroNeSlushaet отделяет «ядра нет на связи» от «ядро ответило отказом».
//
// Разница видна ровно один раз, зато дорого. Команды, меняющие маршрут, ходят
// в clash_api и при отказе НЕ пишут набор: записанный режим, которого ядро не
// знает, показывал бы человеку авто, пока трафик идёт по ручному выбору.
// Рассуждение верное, но оно про ЖИВОЕ ядро.
//
// Когда ядра нет вовсе, расходиться не с чем: трафика через него не идёт
// никакого. Замерено в госте 13.09.2026: авария опускает ядро, человек
// переключает режим в авто, PUT отвергается системой на уровне соединения,
// команда отвечает switch-failed, набор остаётся ручным, и восстановление пять
// минут подряд поднимает ровно тот сервер, который лёг. Выхода из этого у
// человека нет: каждое следующее нажатие попадает в то же окно.
//
// Опознание по числовому коду, а не по тексту: текст Winsock приходит на языке
// системы, см. соседний ResursyMashiny.
func YadroNeSlushaet(err error) bool {
	var errno syscall.Errno
	if !errors.As(err, &errno) {
		return false
	}
	// ECONNREFUSED на не-Windows: пакет собирается под все системы, как и
	// соседний ResursyMashiny.
	return errno == wsaeConnRefused || errors.Is(errno, syscall.ECONNREFUSED)
}
