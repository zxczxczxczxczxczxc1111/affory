// Package fon запускает фоновые горутины так, чтобы паника в одной из них не
// роняла процесс.
//
// Для службы это вопрос сети человека: процесс службы держит туннель и
// защиту, а необработанная паника в любой горутине Go завершает процесс
// целиком. До 1.7.0 перехват стоял только на командах канала, и паника в
// наблюдателе, восстановлении или расписании уносила службу вместе с
// туннелем. Мета-тест internal/kachestvo/gorutiny_test.go держит правило:
// в службе горутины запускаются только отсюда.
package fon

import (
	"context"
	"log"
	"runtime/debug"
	"time"
)

// Zapustit запускает fn своей горутиной. Паника пишется в журнал со стеком и
// дальше не идёт.
func Zapustit(gde string, fn func()) {
	go Vypolnit(gde, fn)
}

// Vypolnit выполняет fn в текущей горутине и сообщает, упала ли она паникой.
func Vypolnit(gde string, fn func()) (upala bool) {
	defer func() {
		if r := recover(); r != nil {
			ZapisatPaniku(gde, r)
			upala = true
		}
	}()
	fn()
	return false
}

// SPovtorom выполняет долгий цикл fn и после паники запускает его ещё ОДИН
// раз через pauza.
//
// Один, а не вечно: цикл, падающий на каждом заходе, крутил бы панику в
// журнал без конца, а второй подряд провал уже говорит, что дефект в
// состоянии, а не в случайности. Отмена ctx во время паузы повтор снимает.
//
// Ответ true значит «сдался»: fn упал паникой дважды, и работы, которую он
// делал, больше нет. Вызывающему решать, чем её заменить: наблюдатель туннеля,
// например, не имеет права оставить туннель без присмотра.
func SPovtorom(ctx context.Context, gde string, pauza time.Duration, fn func()) (sdalsya bool) {
	if !Vypolnit(gde, fn) {
		return false
	}
	t := time.NewTimer(pauza)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return false
	case <-t.C:
	}
	log.Printf("перезапускаю %s после паники", gde)
	if Vypolnit(gde, fn) {
		log.Printf("%s упал паникой второй раз подряд, больше не перезапускаю", gde)
		return true
	}
	return false
}

// ZapisatPaniku пишет панику в журнал со стеком.
//
// Молча проглоченная паника хуже упавшей службы: падение хотя бы видно, а
// проглоченная оставляет работу, которая не делается по причине, которую
// потом не найти.
func ZapisatPaniku(gde string, r any) {
	log.Printf("паника в %s: %v\n%s", gde, r, debug.Stack())
}
