package hranenie

// Шов для внешнего теста `hranenie_test`, и живёт он ЗДЕСЬ, а не в sekrety.go,
// потому что в API продукта ему делать нечего. Ворота Ш1 нашли его как
// экспортированный без единого вызывающего в проде, и это была правда: подмена
// расшифровки нужна только тесту.
//
// Файл с суффиксом `_test.go` компилируется только под тесты, поэтому
// `hranenie.SShovom` виден тесту и невидим всем остальным.

// SShovom подменяет расшифровку. Шифрование остаётся настоящим: подменять оба
// конца значило бы проверять тест тестом.
func SShovom(dir string, rasshifrovat func([]byte) ([]byte, error)) *Shifrovshchik {
	sh := NovyyV(dir)
	sh.rasshifrovat = rasshifrovat
	return sh
}
