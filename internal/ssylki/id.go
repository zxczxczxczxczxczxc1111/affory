package ssylki

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"
)

// Id это устойчивое имя сервера, по которому его выбирают завтра.
//
// Считается от АДРЕСА, ПОРТА и ТРАНСПОРТА, и больше ни от чего. Каждое слагаемое
// выбрано против конкретного отказа:
//
//   - Порядковый номер отпадает: перестановка строк в подписке молча переключила
//     бы человека на другой сервер, а «connect --server 1» означал бы разное в
//     разные дни.
//   - Хеш всей ссылки отпадает: ротация uuid/pbk/sid в подписке меняла бы имя
//     живого сервера, и клиент сообщал бы selected-server-gone о сервере,
//     который никуда не девался. Ротация это штатное событие, а не поломка.
//   - Имя не участвует: переименование в чужой панели не должно превращать
//     сервер в другой. Заодно это снимает вопрос про «+» во фрагменте.
//
// Переезд на другой адрес читается как НОВЫЙ сервер, и это честно: там другой
// ключ REALITY, другая маска и, как правило, другая страна.
func Id(host string, port int, transport string) string {
	// Хост приводится к нижнему регистру: DNS регистронезависим, и «NL.example»
	// с «nl.example» это один сервер. Литерал IPv6 от этого не страдает.
	s := fmt.Sprintf("%s|%d|%s", strings.ToLower(host), port, transport)
	h := sha256.Sum256([]byte(s))
	// Двенадцать шестнадцатеричных знаков. Полный хеш нечитаем в журнале и в
	// команде, а коллизия на списке из десятков серверов невозможна практически.
	return hex.EncodeToString(h[:6])
}
