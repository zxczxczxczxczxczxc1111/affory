// Известные транспорты. Ядро одно и несёт их все.
// До задачи П5 эта таблица делила транспорты на два класса, и граница между
// классами породила дефект, из-за которого пять из шести не поднимались вовсе.
//
// xhttp УБРАН 06.09.2026. Он был единственной причиной,
// по которой клиент собирал ядро из чужого форка, а сервер держал второй демон
// Xray: у апстримного sing-box транспортов ровно пять (http, ws, quic, grpc,
// httpupgrade), у форка Karing тот же список. Цена отказа померена: из 22
// профилей генератора апстримное ядро отвергло ровно семь, и все семь одним и
// тем же `unknown transport type: xhttp`. Плюсов, которые нельзя получить у
// соседей, за ним не нашлось: по отклику и полосе он середняк, а его класс
// живучести (чистый запрос-ответ, проход через CDN) мы не мерили ни разу.
var izvestnyeTransporty = map[string]bool{
	"reality-tcp": true,
	"ws":          true,
	"grpc":        true,
	"hy2":         true,
	"ss":          true,
	// Добавлено 03.09.2026. Ядро умело их и раньше: у protocol/trojan,
	// protocol/vmess и transport/v2rayhttpupgrade в sing-box нет ни одного
	// условия сборки, набор тегов ради них пересобирать не пришлось.
	"httpupgrade": true,
	"trojan":      true,
	"trojan-ws":   true,
	"vmess":       true,
	"vmess-ws":    true,
	// Добавлено 05.09.2026 тем же способом, что и пятёрка выше: не рассуждением,
	// а `sing-box check` нашей сборкой. Anytls входит в ядро без условий сборки,
	// tuic приезжает вместе с `with_quic`, который у нас и так стоит ради hy2.
	// Контрольная проверка с выдуманным типом при этом падает, то есть зелёный
	// результат означает поддержку, а не молчание декодера.
	"anytls": true,
	"tuic":   true,
}

// Izvestnyy отвечает, умеет ли ядро такой транспорт.
func Izvestnyy(transport string) bool { return izvestnyeTransporty[transport] }

// VseTransporty отдаёт реестр списком, в устойчивом порядке.
//
// Нужен тем, кто обязан пройти по набору ЦЕЛИКОМ: словарю имён на экране в
// первую очередь. Копия списка в другом месте разошлась бы с реестром молча, а
// молчаливое расхождение здесь стоит пустой ячейки в списке серверов, которая
// читается как сломанная запись.
func VseTransporty() []string {
	spisok := make([]string, 0, len(izvestnyeTransporty))
	for t := range izvestnyeTransporty {
		spisok = append(spisok, t)
	}
	sort.Strings(spisok)
	return spisok
}

// Vhod это полный список того, что генератор не имеет права выдумать сам.
// Каждое поле здесь появилось потому, что константа на его месте однажды
// оказалась бы ложью в чужой сети.
type Vhod struct {
	Trafik *protokol.PravilaTrafika
	// Сервер, к которому подключаемся.
	Server protokol.Server

	// Kandidaty это адреса ВСЕХ известных серверов, а не только выбранного.
	// Правило петли строится по ним целиком: переключение сервера не должно
	// требовать пересборки правил, а забытый кандидат это петля, которая
	// проявится через неделю при первом же переключении.
	Kandidaty []netip.Addr

	// Servery это ВСЕ кандидаты селектора и urltest, а не только выбранный.
	// Пустой список означает «кандидат один, он же Server»: отдельной ветки под
	// один сервер нет намеренно, две ветки разошлись бы там, где их перестают
	// одинаково проверять.
	Servery []protokol.Server

	// Rezhim решает, что стоит умолчанием селектора: выбранный сервер или группа
	// авто. ПУСТОЕ значение означает ручной, и это сохраняет поведение всех
	// существующих фикстур без правки. Решение «какой режим» продуктовое и
	// живёт в службе; генератор остаётся чистой функцией от входа.
	Rezhim protokol.Rezhim

	// Resolver спрашивается у адаптера в момент подъёма (см. пакет set).
	Resolver netip.Addr

	// PutiProtsessov это полные пути наших бинарей: оба ядра и сама служба, то
	// есть ТРИ (см. putiProtsessov в killswitch.go). Прежний комментарий говорил
	// «ровно два» и остался от времени одного ядра. В "проверенном" конфиге
	// редакции 5 не было службы, и третья петля вернулась бы на повторном
	// резолве по TTL.
	PutiProtsessov []string

	// ClashApi нужен инварианту 7 этой волны и всей волне 6.
	ClashApi ClashApi

	// AdresTun и MaskaTun задают адрес самого TUN-адаптера.
	AdresTun string

	// PortProksi поднимает локальный прокси РЯДОМ с туннелем. Ноль означает
	// «без прокси».
	//
	// Туннеля мало. Приложение, которому задан прокси, в обход него не пойдёт
	// никогда: для HTTP-клиента заданный прокси обязателен, а не желателен. На
	// рабочей машине системный прокси Windows указывал на порт чужого клиента,
	// и с его уходом Claude Code переставал стартовать вовсе, хотя туннель нёс
	// трафик. Поэтому mixed живёт рядом с TUN, как у v2rayN, nekoray и Karing.
	PortProksi int

	// VesTrafik означает режим kill-switch: удобные исключения отменяются,
	// петлевые остаются. Разница принципиальная: без петлевых туннель съедает
	// сам себя, а без удобных всего лишь перестаёт работать принтер.
	VesTrafik bool

	// Nabory это удалённые наборы правил (rule_set). Пустой список означает
	// «доменных наборов нет», и раздела в конфиге тогда нет вовсе.
	Nabory []NaborPravil

	// Protsessy это пути процессов, которые человек попросил вести мимо
	// туннеля (§5 п.1). Уже нормализованные (set.NormalizovatPut): генератор
	// строку не трогает, ядро сравнивает её как есть.
	Protsessy []string

	// Domeny это домены, которые человек попросил вести мимо туннеля, вместе
	// с поддоменами (domain_suffix). Правило держится на сниффинге: в TUN
	// приходят голые адреса, имя достаётся из рукопожатия TLS, и приложение,
	// которое ходит по адресу без имени, под него не попадёт никогда.
	Domeny []string

	// FaylKesha это experimental.cache_file. Без него удалённый набор
	// скачивается на каждом старте и забывается на каждом стопе. Пустое
	// значение означает «без кэша», и это допустимо только без наборов.
	FaylKesha string

	// Полоса КАНАЛА ЧЕЛОВЕКА в мегабитах, вверх и вниз. Ноль в обоих означает
	// «не измерена», и это не то же самое, что ноль объявленный.
	//
	// Она здесь, а не в сервере, потому что она про домашний канал, а не про
	// узел: одна и та же ссылка у одного человека несёт 440 Мбит, у другого 20.
	// Единственное её назначение это hysteria2, у которого объявление полосы и
	// ЕСТЬ переключатель Brutal (отдельного флага у протокола нет). Остальные
	// транспорты её не понимают, и писать её им нельзя.
	//
	// Число обязано быть ИЗМЕРЕННЫМ и с запасом вниз. Замер 05.09.2026: честный
	// Brutal дал 447.8 Мбит и 93 мс против 374.6 и 147 у BBR, а завышенный на
	// 30% откатился к 401.7 и 121 мс. На узком канале завышение хуже всего:
	// объявленные 440 на полке 20 Мбит дали восемь провалов и p95 3214 мс.
	PolosaVverh int
	PolosaVniz  int
}

// ClashApi: секрет случайный на каждый старт, порт от системы. Оба значения
// уезжают в файл состояния, иначе интерфейс волны 6 не найдёт, куда стучаться.
type ClashApi struct {
	Adres  string
	Port   int
	Sekret string
}

var (
	ErrNetKandidatov = errors.New("пустой список кандидатов: правило петли будет неполным")
	ErrNetProtsessov = errors.New("нужны пути обоих процессов: ядра и службы")
	ErrNetResolvera  = errors.New("не задан локальный резолвер")
	ErrTransport     = errors.New("транспорт не поддержан")
	// Полоса объявляется ПАРОЙ или не объявляется вовсе. Brutal управляет
	// обоими направлениями сразу, и одно число означало бы нулевое второе, то
	// есть объявленный ноль вместо «не знаю».
	ErrPolosaNepolnaya = errors.New("полоса канала задана только в одну сторону")
)

func (v Vhod) proverit() error {
	if err := proveritMarshruty(v); err != nil {
		return err
	}
	switch {
	case len(v.Kandidaty) == 0:
		return ErrNetKandidatov
	case len(v.PutiProtsessov) < 2:
		return ErrNetProtsessov
	case !v.Resolver.IsValid():
		return ErrNetResolvera
	case !Izvestnyy(v.Server.Transport):
		return fmt.Errorf("%w: %s", ErrTransport, v.Server.Transport)
	case (v.PolosaVverh > 0) != (v.PolosaVniz > 0):
		return fmt.Errorf("%w: вверх %d, вниз %d", ErrPolosaNepolnaya, v.PolosaVverh, v.PolosaVniz)
	case v.PolosaVverh < 0 || v.PolosaVniz < 0:
		return fmt.Errorf("%w: отрицательная полоса вверх %d, вниз %d",
			ErrPolosaNepolnaya, v.PolosaVverh, v.PolosaVniz)
	}
	return nil
}
