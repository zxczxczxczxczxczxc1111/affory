package main

import (
	"reflect"
	"testing"
)

// Швы существуют ради тестов, и в этом же их опасность: фикстура подставляет
// свои значения, поэтому НЕ ЗАПОЛНЕННЫЙ конструктором шов не виден ни одному
// тесту и стреляет только в проде.
//
// Замерено 01.09.2026: правка вырезала из конструктора две строки (zamerit и
// zhdatKlash), все тесты остались зелёными, а живая служба падала при connect
// с обрывом журнала на полуслове. Этот тест закрывает весь класс сразу.
func TestKonstruktorZapolnyaetVseShvy(t *testing.T) {
	s := NovayaSluzhba()
	// Через указатель, а не значением: копия структуры утащила бы с собой
	// мьютекс, и vet справедливо ругается на это.
	v := reflect.ValueOf(s).Elem()
	tp := v.Type()
	for i := 0; i < v.NumField(); i++ {
		if v.Field(i).Kind() != reflect.Func {
			continue
		}
		// otmena это не шов, а состояние: функция отмены живого подключения.
		// До первого connect её нет и быть не должно.
		// То же про otmenaVosst: отмена живого восстановления, которого до
		// первой аварии не существует.
		// И statOtmena: отмена опроса статистики, которого без подписчиков нет.
		switch tp.Field(i).Name {
		case "otmena", "otmenaVosst", "statOtmena":
			continue
		}
		if v.Field(i).IsNil() {
			t.Errorf("шов %s не заполнен: в проде это паника при первом вызове", tp.Field(i).Name)
		}
	}
}
