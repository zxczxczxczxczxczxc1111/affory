// Подготовка кандидата до остановки рабочего подключения (A6, 22.09.2026).
//
// Было так: перезапуск ради новых правил начинался с Disconnect, и только потом
// собирался конфиг, который ядро могло не принять. Человек с негодным набором
// правил оставался без VPN, а причина приезжала отдельной строкой уже после
// того, как туннель упал. Порядок «сначала уроним, потом посмотрим» стоит
// дорого ровно тогда, когда новое негодно - то есть в том самом случае, ради
// которого проверка и нужна.
//
// Стало: конфиг собирается и отдаётся ядру на проверку ПОКА СТАРЫЙ РАБОТАЕТ.
// Не принят - рабочее подключение остаётся нетронутым, а вызывающий откатывает
// свою правку. Образец тот же, что у Clash Verge Rev: подготовить, проверить,
// применить.
//
// Проверка идёт ТЕМ ЖЕ путём, что и боевая сборка (sobratTunProverennyy),
// включая круг исключения серверов, которых ядро не принимает. Иначе кандидат
// браковался бы там, где подъём прошёл бы: одна негодная запись чужой подписки
// это обычное дело, и боевой путь её исключает.

var errKandidatNegoden = errors.New("новый конфиг не принят ядром")

func putKandidata() string {
	return sostoyanie.KatalogDannyh() + `\sing-box.kandidat.json`
}

// Шов ради теста, как putKonfigaVybora рядом: настоящая пишет в служебный
// каталог машины, а тест не должен трогать машину, на которой идёт.
var putKandidataFayl = putKandidata

// proveritKandidata отвечает, поднимется ли туннель с ТЕКУЩИМ набором.
//
// Файл отдельный от рабочего и удаляется за собой. Писать кандидата поверх
// рабочего конфига нельзя: живое ядро судят по файлу и восстановление после
// нештатной смерти службы читает его же, а на диске оказался бы конфиг, с
// которым никто не поднимался.
func (s *Sluzhba) proveritKandidata() error {
	if s.proveritKonfig == nil {
		// Проверять нечем: в тестах и на машине без ядра это не отказ, а
		// отсутствие судьи. Отказывать здесь значило бы запретить применение
		// правил всякий раз, когда ядро не на месте.
		return nil
	}
	put := putKandidataFayl()
	defer func() {
		if err := os.Remove(put); err != nil && !os.IsNotExist(err) {
			log.Printf("файл кандидата не убран: %v", err)
		}
	}()
	if _, _, err := s.sobratTunProverennyy(put, true); err != nil {
		return fmt.Errorf("%w: %v", errKandidatNegoden, err)
	}
	return nil
}

// vernutPravila возвращает набор к прежним правилам.
//
// Отвечает УСПЕХОМ или неуспехом, а не молчит: отказ записи здесь означает, что
// на диске остались правила, которых ядро не принимает, и человеку надо сказать
// об этом словами, а не оставить его с исправным на вид списком.
func (s *Sluzhba) vernutPravila(bylo PravilaNabora) bool {
	if err := s.pravitNabor(func(n *Nabor) error {
		n.Pravila = bylo
		return nil
	}); err != nil {
		log.Printf("прежние правила не вернулись после отказа кандидата: %v", err)
		return false
	}
	return true
}
