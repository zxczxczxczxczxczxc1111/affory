// Осиротевшие правила сервисов.
//
// Каталог сервисов едет ВНУТРИ программы и меняется с её выпусками: WhatsApp и
// Netflix ушли из него 16.09.2026. Правило, записанное прежней версией,
// остаётся лежать в наборе и указывает в пустоту.
//
// Жалоба 21.09.2026 показала, во что это обходилось. Человек обновился с 1.0.3
// сразу на 1.4.1, и сборка конфига падала на «неизвестный сервис whatsapp»
// КАЖДЫЙ раз: подключиться было нельзя вовсе. Снять правило в окне тоже было
// нельзя - окно рисует список из каталога, а сервиса в каталоге больше нет.
// Более того, переключение любого другого сервиса отправляло осиротевшее
// правило обратно и получало отказ на весь список.
//
// Это ТОТ ЖЕ тупик, что уже описан у proveritPravila про снесённую с диска
// игру, и лечится он так же: осиротевшее правило не делает список негодным, оно
// просто перестаёт существовать.

// PrivestiPravila убирает из набора правила сервисов, которых каталог этой
// версии не знает.
//
// Зовётся на КАЖДОМ чтении набора, поэтому идемпотентна: второй проход по
// приведённому набору не меняет ничего и не говорит ничего.
//
// Возвращает список починок, по строке на каждую. Молчаливая правка набора
// стоила разбору жалобы про подписки трёх заходов вслепую, и повторять это
// незачем.
func (n *Nabor) PrivestiPravila() []string {
	if n.Pravila.Trafik == nil || len(n.Pravila.Trafik.Servisy) == 0 {
		return nil
	}
	ostalis := make([]protokol.PraviloServisa, 0, len(n.Pravila.Trafik.Servisy))
	var pochinki []string
	for _, s := range n.Pravila.Trafik.Servisy {
		if katalog.Est(s.Id) {
			ostalis = append(ostalis, s)
			continue
		}
		pochinki = append(pochinki, fmt.Sprintf(
			"правило сервиса %q снято: каталог этой версии такого сервиса не знает", s.Id))
	}
	if len(pochinki) == 0 {
		return nil
	}
	n.Pravila.Trafik.Servisy = ostalis
	return pochinki
}
